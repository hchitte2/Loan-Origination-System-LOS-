export function makeIcons(React) {
  const cache = {};
  const icon = (name, size = 16, extra) => {
    const key = name + size;
    if (!extra && cache[key]) return cache[key];
    const el = React.createElement("svg", {
      width: size,
      height: size,
      viewBox: "0 0 24 24",
      fill: "none",
      stroke: "currentColor",
      strokeWidth: 2,
      strokeLinecap: "round",
      strokeLinejoin: "round",
      "aria-hidden": true,
      style: Object.assign({ flex: "none", display: "block" }, extra || {}),
      dangerouslySetInnerHTML: { __html: P[name] || P.circle },
    });
    if (!extra) cache[key] = el;
    return el;
  };
  const i16 = {},
    i20 = {},
    i24 = {};
  Object.keys(P).forEach((k) => {
    i16[k] = icon(k, 16);
    i20[k] = icon(k, 20);
    i24[k] = icon(k, 24);
  });
  return { icon, i16, i20, i24, names: Object.keys(P) };
}
